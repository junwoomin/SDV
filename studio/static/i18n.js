let savedLanguage='ko';
try { savedLanguage=localStorage.getItem('sdv-language')==='en'?'en':'ko'; } catch {}
export const language=savedLanguage;
export const locale=language==='en'?'en-US':'ko-KR';
const escapeRegex=text=>text.replace(/[.*+?^$\x7b\x7d()|[\]\\]/g,'\\$&');
const pattern=new RegExp(Object.keys(en).sort((a,b)=>b.length-a.length).map(escapeRegex).join('|'),'g');
const cache=new Map();
export function t(source){
  if(typeof source!=='string')throw new TypeError('t() requires a static UI string.');
  if(language==='ko')return source;
  if(cache.has(source))return cache.get(source);
  const result=Object.hasOwn(en,source)?en[source]:source.replace(pattern,matched=>en[matched]);
  cache.set(source,result);return result;
}
const templateCache=new WeakMap();
export function h(strings,...values){
  let parts=templateCache.get(strings);
  if(!parts){parts=Array.from(strings,t);templateCache.set(strings,parts);}
  return parts.reduce((result,part,index)=>result+part+(index<values.length?String(values[index]):''),'');
}
export function setLanguage(value){
  if(value!=='ko'&&value!=='en')throw new Error('Unsupported UI language.');
  localStorage.setItem('sdv-language',value);
}
